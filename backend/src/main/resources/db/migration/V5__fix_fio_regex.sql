-- ФИО с двойной фамилией: паттерн V2 не поддерживал дефис,
-- из-за чего "Сидорова-Водкина Анна Сергеевна" извлекалось как "Водкина Анна Сергеевна".
UPDATE template_field
SET regex_pattern = '(?<value>[А-ЯЁ][а-яё]*(?:-[А-ЯЁ][а-яё]*)*(?:\s+[А-ЯЁ][а-яё]*(?:-[А-ЯЁ][а-яё]*)*){1,2})'
WHERE field_code = 'borrower_fio';
